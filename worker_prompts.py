def _get_available_documents() -> str:
    file_list = []
    for d in DATA_DIRS:
        if os.path.exists(d):
            for f in os.listdir(d):
                if f.endswith((".md", ".pdf", ".txt")):
                    file_list.append(f)
    return "\n- ".join(file_list) if file_list else "ไม่พบเอกสาร"


